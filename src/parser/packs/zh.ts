function numberWords(text: string): string {
  let t = cjkNumeralsToDigits(expandK(text));
  // "12块5" / "十二块五毛" -> 12.5块
  t = t.replace(/(\d+)(块钱|块|元)(\d)(?:毛|角)?(?!\d)/g, '$1.$3$2');
  t = t.replace(/(\d+)\s?(块|元)\s?(\d)\s?(?:毛|角)/g, '$1.$3$2');
  return t;
}

